export const USD_TO_TZS_RATE = 2600;

export function formatUSD(val: number): string {
  return `$${val.toFixed(2)}`;
}

export function formatTZS(val: number): string {
  const tzs = Math.round(val * USD_TO_TZS_RATE);
  return `TSh ${tzs.toLocaleString()}`;
}

export function formatDualCurrency(usd: number): string {
  return `${formatUSD(usd)} ≈ ${formatTZS(usd)}`;
}

