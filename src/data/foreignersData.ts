// Swahili day & month names for authentic Tanzanian dynamic dates
const SWAHILI_DAYS = [
  'Jumapili',
  'Jumatatu',
  'Jumanne',
  'Jumatano',
  'Alhamisi',
  'Ijumaa',
  'Jumamosi',
];

const SWAHILI_MONTHS = [
  'Januari',
  'Februari',
  'Machi',
  'Aprili',
  'Mei',
  'Juni',
  'Julai',
  'Agosti',
  'Septemba',
  'Oktoba',
  'Novemba',
  'Desemba',
];

export function getSwahiliDateString(date: Date = new Date()): {
  fullDate: string;
  shortDate: string;
  dayName: string;
  dayNumber: number;
  monthName: string;
  year: number;
} {
  const dayName = SWAHILI_DAYS[date.getDay()];
  const dayNumber = date.getDate();
  const monthName = SWAHILI_MONTHS[date.getMonth()];
  const year = date.getFullYear();

  return {
    fullDate: `${dayName}, ${dayNumber} ${monthName} ${year}`,
    shortDate: `${dayNumber} ${monthName}`,
    dayName,
    dayNumber,
    monthName,
    year,
  };
}

// Daily rotation engine: picks 16 distinct foreigners based on the exact day of the year so each day is DIFFERENT
export function getDailyForeigners(date: Date = new Date(), offset: number = 0): ForeignerProfile[] {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));

  const total = ALL_FOREIGNERS.length; // 36 total wazungu in master catalog
  const count = 16; // Exactly 16 foreigners shown on the site

  // Shift offset changes every single day (dayOfYear * 7 + offset * 5) so every day features different wazungu
  const dailyShift = Math.abs(dayOfYear * 7 + offset * 5) % total;

  const result: ForeignerProfile[] = [];
  for (let i = 0; i < count; i++) {
    const index = (dailyShift + i) % total;
    result.push(ALL_FOREIGNERS[index]);
  }

  return result;
}
